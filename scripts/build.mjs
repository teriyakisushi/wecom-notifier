#!/usr/bin/env node
import { build } from 'esbuild';
import { existsSync, mkdirSync, readFileSync, rmSync, statSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(fileURLToPath(import.meta.url));
const repoRoot = dirname(root);
const outfile = join(repoRoot, 'dist', 'index.mjs');
const check = process.argv.includes('--check');

const buildOptions = {
  entryPoints: [join(repoRoot, 'src', 'cli.mjs')],
  outfile: check ? join(repoRoot, 'dist', '.index.check.mjs') : outfile,
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node18',
  legalComments: 'none',
  charset: 'utf8',
  logLevel: 'silent',
  banner: {
    js: [
      '// Generated by scripts/build.mjs. Do not edit by hand.',
      "import { createRequire as __createRequire } from 'node:module';",
      'const require = __createRequire(import.meta.url);',
    ].join('\n'),
  },
};

function fail(message) {
  console.error(`build: ${message}`);
  process.exitCode = 1;
}

function formatBytes(bytes) {
  if (bytes < 1024) return `${bytes} B`;
  return `${(bytes / 1024).toFixed(1)} KB`;
}

mkdirSync(join(repoRoot, 'dist'), { recursive: true });

try {
  await build(buildOptions);
} catch (error) {
  fail(error?.message || String(error));
  process.exit(1);
}

if (!check) {
  const size = statSync(outfile).size;
  console.log(`built ${relative(repoRoot, outfile)} (${formatBytes(size)})`);
  process.exit(0);
}

const checkFile = buildOptions.outfile;
try {
  if (!existsSync(outfile)) {
    fail(`missing ${relative(repoRoot, outfile)}; run \`npm run build\``);
  } else {
    const expected = readFileSync(outfile);
    const actual = readFileSync(checkFile);
    if (!expected.equals(actual)) {
      fail(`${relative(repoRoot, outfile)} is out of date; run \`npm run build\` and commit it`);
    } else {
      console.log(`dist is up to date (${formatBytes(expected.length)})`);
    }
  }
} finally {
  rmSync(checkFile, { force: true });
}
